/// Item 53 — what goes inside a backup, and how it comes back.
///
/// [backup_file.dart] locks the thing; this decides what the thing is.
///
/// Two rules shape all of it. First, restore **replaces** what is on the
/// phone, so it has to be all-or-nothing: a half-applied restore is worse
/// than a failed one, because the half that was there before is gone and
/// the half that arrived cannot be trusted. Everything here runs in one
/// transaction.
///
/// Second, a backup outlives the build that wrote it. Someone restores a
/// file made four versions ago onto a phone whose schema has moved. So the
/// columns are matched by name at restore time against the schema that
/// exists *now*: a column the backup does not carry takes its default, and
/// one the app no longer has is dropped. Neither is an error, and both are
/// reported.
library;

import 'dart:io';

import 'package:drift/drift.dart';
import 'package:flutter/foundation.dart' show immutable;
import 'package:path/path.dart' as p;

import '../data/db.dart';
import 'backup_file.dart';

/// Bumped when the shape of the payload changes in a way an older app
/// could not read. Adding a table does not need it — an older app simply
/// skips a table it does not have.
const int kBackupPayloadVersion = 1;

/// The tables that hold the user's own record.
///
/// Listed rather than discovered so that adding a table is a decision
/// somebody makes, not something that silently starts being copied into
/// everyone's backups.
const List<String> kBackupTables = [
  'activity_sessions',
  'samples',
  'route_points',
  'journal_entries',
  'patterns',
  'user_activities',
  'practice_targets',
  'cycle_days',
  'meals',
  'guide_persona_prefs',
  'guide_voice_prefs',
  'ring_history_caches',
  'ring_orders',
  'ecg_recordings',
  'weekly_plans',
  'chat_sessions',
  'chat_messages',
];

/// Left out, and why.
///
/// `raw_sdk_events` is a diagnostic log of what the ring hardware said. It
/// is large, it is regenerated by the next sync, and nobody would miss it
/// on a new phone — the same reasoning that leaves the model and the voice
/// out of the file.
const List<String> kBackupExcludedTables = ['raw_sdk_events'];

/// What a restore did, in enough detail to tell someone.
@immutable
class BackupRestoreReport {
  const BackupRestoreReport({
    required this.rowsByTable,
    required this.skippedTables,
    required this.skippedColumns,
    this.photos = 0,
  });

  /// Rows written, per table.
  final Map<String, int> rowsByTable;

  /// Tables in the backup that this build no longer has.
  final List<String> skippedTables;

  /// Columns in the backup that this build no longer has, as
  /// `table.column`.
  final List<String> skippedColumns;

  /// Meal photos written back.
  final int photos;

  int get totalRows =>
      rowsByTable.values.fold(0, (sum, count) => sum + count);

  bool get isEmpty => totalRows == 0;

  /// One line, for the screen. Counts rather than table names, because
  /// "4,812 records" is the thing a person can check against their memory
  /// of using the app.
  String get summary {
    final rows = totalRows;
    final label = rows == 1 ? 'record' : 'records';
    if (photos == 0) return '$rows $label restored';
    final photoLabel = photos == 1 ? 'photo' : 'photos';
    return '$rows $label and $photos $photoLabel restored';
  }

  BackupRestoreReport withPhotos(int count) => BackupRestoreReport(
        rowsByTable: rowsByTable,
        skippedTables: skippedTables,
        skippedColumns: skippedColumns,
        photos: count,
      );
}

/// The meal photos a backup should carry, keyed by file name.
///
/// Photos are files rather than rows, and unlike the model and the voice
/// they do not download again — a restore without them hands someone their
/// meals with the pictures missing. They are collected by name, not by
/// path, because [resolveMealPhoto] looks them up by name on the way back:
/// a photo restored onto a different phone lands in that phone's meals
/// folder and the stored path still finds it.
///
/// Readers rather than bytes, so the caller holds one photo at a time.
Future<Map<String, BackupFileReader>> collectMealPhotos({
  required VyanaDatabase db,
  required String mealPhotosPath,
}) async {
  if (!await _tableExists(db, 'meals')) return const {};
  final rows = await db
      .customSelect('SELECT photo_path FROM meals WHERE photo_path IS NOT NULL')
      .get();

  final files = <String, BackupFileReader>{};
  for (final row in rows) {
    final stored = row.data['photo_path'] as String?;
    if (stored == null || stored.trim().isEmpty) continue;
    final name = p.basename(stored);
    if (files.containsKey(name)) continue;

    // Where it is now, which after item 59 may not be where it was saved.
    final candidates = [File(stored), File(p.join(mealPhotosPath, name))];
    for (final file in candidates) {
      if (file.existsSync()) {
        files[name] = () => file.readAsBytes();
        break;
      }
    }
  }
  return files;
}

/// Writes restored photos into this phone's meals folder.
///
/// By name, so the absolute paths in the restored rows do not have to be
/// rewritten — [resolveMealPhoto] already falls back to the name under the
/// current folder, which is what makes a backup portable between phones.
Future<int> restoreMealPhotos({
  required Map<String, Uint8List> files,
  required String mealPhotosPath,
}) async {
  if (files.isEmpty) return 0;
  final dir = Directory(mealPhotosPath);
  await dir.create(recursive: true);
  var written = 0;
  for (final entry in files.entries) {
    final target = File(p.join(mealPhotosPath, p.basename(entry.key)));
    await target.writeAsBytes(entry.value, flush: true);
    written++;
  }
  return written;
}

/// Reads the whole vault, plus [settings], into the map that gets encrypted.
///
/// [settings] is passed in rather than read here so this stays a pure
/// function of the database and a map — which is what makes it testable
/// without a platform.
Future<Map<String, Object?>> buildBackupPayload({
  required VyanaDatabase db,
  required Map<String, Object?> settings,
  DateTime? now,
}) async {
  final tables = <String, Object?>{};
  for (final table in kBackupTables) {
    if (!await _tableExists(db, table)) continue;
    final rows = await db.customSelect('SELECT * FROM $table').get();
    tables[table] = [for (final row in rows) row.data];
  }

  return {
    'payloadVersion': kBackupPayloadVersion,
    'createdAt': (now ?? DateTime.now()).toUtc().toIso8601String(),
    'schemaVersion': db.schemaVersion,
    'settings': settings,
    'tables': tables,
  };
}

/// Puts a backup back, replacing what is on the phone.
///
/// Throws if [payload] was written by a newer build than this one knows how
/// to read — the caller has already checked the *file* version, but the
/// payload carries its own and they can move independently.
///
/// Everything happens in one transaction. If any part of it throws, nothing
/// is written and the vault is exactly as it was.
Future<BackupRestoreReport> restoreBackupPayload({
  required VyanaDatabase db,
  required Map<String, Object?> payload,
}) async {
  final version = payload['payloadVersion'];
  if (version is int && version > kBackupPayloadVersion) {
    throw StateError(
      'This backup holds data from a newer version of Vyana '
      '(payload $version, this build reads $kBackupPayloadVersion).',
    );
  }

  final raw = payload['tables'];
  final tables = raw is Map ? Map<String, Object?>.from(raw) : const {};

  final rowsByTable = <String, int>{};
  final skippedTables = <String>[];
  final skippedColumns = <String>[];

  await db.transaction(() async {
    // Children before parents: chat_messages has a cascade onto
    // chat_sessions, and deleting the parent first would take the rows we
    // are about to count with it.
    for (final table in kBackupTables.reversed) {
      if (!tables.containsKey(table)) continue;
      if (!await _tableExists(db, table)) {
        skippedTables.add(table);
        continue;
      }
      await db.customStatement('DELETE FROM $table');
    }

    for (final table in kBackupTables) {
      final rows = tables[table];
      if (rows is! List) continue;
      if (skippedTables.contains(table)) continue;
      if (!await _tableExists(db, table)) continue;

      final columnsNow = await _columns(db, table);
      var written = 0;

      for (final row in rows) {
        if (row is! Map) continue;
        final values = Map<String, Object?>.from(row);

        final usable = <String>[];
        for (final column in values.keys) {
          if (columnsNow.contains(column)) {
            usable.add(column);
          } else {
            final key = '$table.$column';
            if (!skippedColumns.contains(key)) skippedColumns.add(key);
          }
        }
        if (usable.isEmpty) continue;

        final placeholders = List.filled(usable.length, '?').join(', ');
        await db.customInsert(
          'INSERT OR REPLACE INTO $table (${usable.join(', ')}) '
          'VALUES ($placeholders)',
          variables: [for (final c in usable) Variable(values[c])],
        );
        written++;
      }
      rowsByTable[table] = written;
    }
  });

  return BackupRestoreReport(
    rowsByTable: rowsByTable,
    skippedTables: skippedTables,
    skippedColumns: skippedColumns,
  );
}

/// The settings a backup carries: the user's own, not the device's.
///
/// Keys are listed rather than taken wholesale because the preferences also
/// hold things that belong to *this phone* — a paired ring's MAC address, a
/// pending storage migration, which models are downloaded. Restoring those
/// onto a different handset would describe a phone that does not exist.
///
/// Item 97: these are the keys the app itself passes to SharedPreferences.
/// The plugin adds its own `flutter.` prefix on disk; asking for
/// `flutter.vyana.user_profile` through the API looks for
/// `flutter.flutter.vyana.user_profile` and always finds nothing.
const List<String> kBackupSettingKeys = [
  'vyana.user_profile',
  'vyana.practice.pins',
  'vyana_voice_cues_enabled',
  'guide_voice_responses_enabled_v1',
  'guide_selected_voice_json_v1',
];

/// Settings deliberately left on the phone they belong to.
const List<String> kBackupExcludedSettingKeys = [
  'vyana.paired_prana_ring',
  'vyana.storage.old_root_pending_delete',
];

Future<bool> _tableExists(VyanaDatabase db, String table) async {
  final rows = await db
      .customSelect(
        "SELECT name FROM sqlite_master WHERE type='table' AND name = ?",
        variables: [Variable(table)],
      )
      .get();
  return rows.isNotEmpty;
}

Future<Set<String>> _columns(VyanaDatabase db, String table) async {
  final rows = await db.customSelect('PRAGMA table_info($table)').get();
  return {for (final row in rows) row.data['name'] as String};
}
